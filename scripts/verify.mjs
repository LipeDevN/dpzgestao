import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('artifacts', {recursive:true});
const browser = await chromium.launch({channel:'chrome', headless:true});
const report = {errors:[], missing:[], checks:[]};
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror', e=>report.errors.push(e.message));
  page.on('response', r=>{if(r.status()>=400) report.missing.push(`${r.status()} ${r.url()}`)});
  await page.goto('http://localhost:4173', {waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForTimeout(1700);
  await page.screenshot({path:'artifacts/desktop.png',animations:'disabled'});
  const localGeometry = await page.locator('.cs-hero, .ph-nav, #simulador').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {class:n.className,x:r.x,y:r.y,width:r.width,height:r.height}}));
  assert.equal(await page.locator('img').evaluateAll(images=>images.filter(i=>!i.complete||i.naturalWidth===0).length),0);
  report.checks.push('All images loaded');
  const before = await page.locator('#simParcela').textContent();
  await page.locator('#simValue').evaluate(el=>{el.value='600000';el.dispatchEvent(new Event('input',{bubbles:true}))});
  assert.notEqual(await page.locator('#simParcela').textContent(),before);
  await page.locator('[data-type="veiculo"]').click();
  assert.equal((await page.locator('#simTypeDisplay').textContent()).trim(),'Veículo');
  report.checks.push('Simulator responds to amount and type');
  await page.locator('.ph-faq-question').first().click();
  assert.ok(await page.locator('.ph-faq-item').first().evaluate(el=>el.classList.contains('active')));
  report.checks.push('FAQ expands');
  await page.evaluate(()=>openLeadModal());
  await page.locator('#leadNome').fill('Teste local');
  await page.locator('#leadEmail').fill('teste@example.com');
  await page.locator('#leadTelefone').fill('11987654321');
  assert.equal(await page.locator('#leadTelefone').inputValue(),'(11) 98765-4321');
  await page.evaluate(()=>{window.open=(url)=>{window.testDestination=url;return null}});
  await page.locator('#leadSubmitBtn').click();
  const destination = await page.evaluate(()=>window.testDestination);
  assert.ok(destination.startsWith('https://wa.me/551147651770?text='));
  assert.ok(decodeURIComponent(destination).includes('Teste local'));
  report.checks.push('Form validation, phone mask and WhatsApp message (no data sent)');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#leadModal').evaluate(el=>el.classList.contains('open')),false);
  const reference = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  await reference.goto('https://phcorretora.com.br/',{waitUntil:'networkidle'});
  await reference.evaluate(()=>document.fonts.ready);
  await reference.waitForTimeout(1700);
  await reference.screenshot({path:'artifacts/original-desktop.png',animations:'disabled'});
  report.geometry = {local:localGeometry,original:await reference.locator('.cs-hero, .ph-nav, #simulador').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {class:n.className,x:r.x,y:r.y,width:r.width,height:r.height}}))};
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://localhost:4173',{waitUntil:'networkidle'});
  await page.waitForTimeout(1000);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/mobile.png',animations:'disabled'});
  await page.locator('#navToggle').click();
  assert.ok(await page.locator('#mobileMenu').evaluate(el=>el.classList.contains('open')));
  await page.locator('#mobileClose').click();
  assert.equal(await page.locator('#mobileMenu').evaluate(el=>el.classList.contains('open')),false);
  report.checks.push('Mobile layout without overflow and mobile menu');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://localhost:4173', {waitUntil:'networkidle'});
  await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=700){scrollTo(0,y);await new Promise(r=>setTimeout(r,90))}scrollTo(0,0)});
  await page.waitForTimeout(800);
  await page.screenshot({path:'artifacts/full-page.png',fullPage:true,animations:'disabled'});
  assert.deepEqual(report.errors,[]);
  assert.deepEqual(report.missing,[]);
  await writeFile('artifacts/report.json', JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
} finally {await browser.close()}
