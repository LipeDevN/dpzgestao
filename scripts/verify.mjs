import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const port=43179;
await mkdir('artifacts',{recursive:true});
const server=spawn(process.execPath,['scripts/serve.mjs'],{env:{...process.env,PORT:String(port)},windowsHide:true,stdio:['ignore','pipe','pipe']});
let browser;
const report={errors:[],failed:[],checks:[]};
try {
  await new Promise((resolve,reject)=>{const timeout=setTimeout(()=>reject(new Error('Server timeout')),10000);server.once('error',reject);server.stdout.once('data',()=>{clearTimeout(timeout);resolve()});server.stderr.once('data',data=>{clearTimeout(timeout);reject(new Error(data.toString()))})});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>report.errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)report.failed.push(r.url())});
  await page.goto(`http://127.0.0.1:${port}`,{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  assert.match(await page.title(),/DPZ/);
  const body=await page.locator('body').innerText();
  assert.doesNotMatch(body,/PH Neg|PH CORRETORA|consórcio|75.000|500M|18 anos/i);
  assert.ok(body.includes('60.739.583/0001-07'));
  assert.equal(await page.locator('a[href^="https://wa.me"],a[href^="mailto:"],a[href^="tel:"]').count(),0);
  assert.equal(await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||!i.naturalWidth).length),0);
  report.checks.push('DPZ branding, company data, image loaded, no PH contact links');
  await page.screenshot({path:'artifacts/dpz-desktop.png',animations:'disabled'});
  await page.locator('#tab-administrativo').click();
  assert.equal(await page.locator('#selectedService').textContent(),'Administrativo');
  await page.locator('#tab-administrativo').press('ArrowRight');
  assert.equal(await page.locator('#selectedService').textContent(),'Consultoria');
  assert.equal(await page.locator('#servicePanel').getAttribute('aria-labelledby'),'tab-consultoria');
  report.checks.push('Service selection via click and keyboard');
  await page.locator('.ph-faq-question').first().click();
  assert.equal(await page.locator('.ph-faq-question').first().getAttribute('aria-expanded'),'true');
  await page.locator('.ph-faq-question').nth(1).click();
  assert.equal(await page.locator('.ph-faq-question').first().getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('.ph-faq-question').nth(1).getAttribute('aria-expanded'),'true');
  report.checks.push('FAQ opens and closes accessibly');
  const brokenAnchors=await page.locator('a[href^="#"]').evaluateAll(links=>links.filter(link=>!document.getElementById(link.hash.slice(1))).map(link=>link.hash));
  assert.deepEqual(brokenAnchors,[]);
  const map=await page.locator('a[href*="google.com/maps"]').getAttribute('href');
  assert.match(decodeURIComponent(map),/3228.*Porto Alegre/);
  report.checks.push('All internal anchors and map destination');
  await page.evaluate(async()=>{for(let top=0;top<document.body.scrollHeight;top+=500){scrollTo({top,behavior:'instant'});await new Promise(r=>setTimeout(r,100))}scrollTo({top:0,behavior:'instant'})});
  await page.waitForTimeout(800);
  await page.screenshot({path:'artifacts/dpz-full-page.png',fullPage:true,animations:'disabled'});
  for(const width of [390,320,768]) {
    await page.setViewportSize({width,height:844});
    await page.goto(`http://127.0.0.1:${port}`,{waitUntil:'networkidle'});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
    await page.locator('#navToggle').click();
    assert.equal(await page.locator('#navToggle').getAttribute('aria-expanded'),'true');
    await page.locator('#mobileClose').click();
    assert.equal(await page.locator('#navToggle').getAttribute('aria-expanded'),'false');
    await page.locator('#navToggle').click();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#navToggle').getAttribute('aria-expanded'),'false');
    if(width===390)await page.screenshot({path:'artifacts/dpz-mobile.png',animations:'disabled'});
  }
  report.checks.push('Mobile menu, Escape key, no overflow at 320/390/768px');
  assert.deepEqual(report.errors,[]);assert.deepEqual(report.failed,[]);
  assert.equal((await fetch(`http://127.0.0.1:${port}/`)).status,200);
  assert.equal((await fetch(`http://127.0.0.1:${port}/package.json`)).status,404);
  report.checks.push('Railway PORT and healthcheck, source files not served');
  await writeFile('artifacts/dpz-report.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
}finally{if(browser)await browser.close();server.kill()}
